#!/usr/bin/env python3
"""Write analysis/INDEX.md, a read-only map of the tracked files under analysis/.

The index groups what is already there. It moves, renames and rewrites nothing:
hundreds of tracked records pin analysis/ paths and SHA256 hashes, so the files
must stay where they are. The file list comes from `git ls-files`, so untracked
run outputs and local scratch files never enter the index.

    python3 scripts/hygiene/index_analysis.py          # rewrite analysis/INDEX.md
    python3 scripts/hygiene/index_analysis.py --check  # exit 1 if it is out of date

Only the Python standard library and git are needed.
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = 'analysis/INDEX.md'
COMMAND = 'python3 scripts/hygiene/index_analysis.py'

# Studies that describe the current EMPF default. Hand-maintained; each entry
# names a directory under analysis/. Order is reading order.
CURRENT = (
    ('default_empf_20261117', 'Owner selection of native EMPF as the CLI default; runtime setup'),
    ('empf_comparison_20261117', 'Fixed fold 0/seed 0 comparison of EMPF against the 0.9.7 default'),
    ('coverage_empf_20261117', 'Coverage pilot: quarter-contraction readout and SD-only calibration'),
    ('coverage_empf_confirm_20261120', 'In progress: 17-fit fold/seed confirmation of the default and readout'),
    ('particlegan_review_20261117', 'CPU probe of EMPF conditional residual at wide input widths'),
    ('particlegan_upgrade_20261117', 'Isolated ParticleGAN 0.10.0 release test'),
)
ENTRY_POINTS = ('README.md', 'README.txt', 'PROTOCOL.md', 'PROTOCOL.txt', 'TAKEOVER.txt')
DATE = re.compile(r'(?<!\d)(20\d{6})(?!\d)')
MIN_FAMILY = 3
TOP_COPY_GROUPS = 15


def tracked(root: Path = ROOT) -> list[tuple[str, str]]:
    """Return sorted (path, blob id) for every tracked file under analysis/."""
    out = subprocess.run(['git', '-C', str(root), 'ls-files', '-s', '-z', '--', 'analysis'],
                         check=True, capture_output=True).stdout.decode()
    rows = []
    for entry in filter(None, out.split('\0')):
        meta, path = entry.split('\t', 1)
        rows.append((path, meta.split()[1]))
    return sorted(rows)


def family(name: str) -> str:
    stem = name.split('.', 1)[0]
    return stem.split('_', 1)[0] or stem


def dates(names) -> str:
    found = sorted({d for n in names for d in DATE.findall(n)})
    if not found:
        return ''
    return found[0] if len(found) == 1 else f'{found[0]}-{found[-1]}'


def cell(text: str) -> str:
    return text.replace('|', '\\|')


def render(rows: list[tuple[str, str]]) -> str:
    """Render the index from (path, blob id) rows. Pure, so it is unit-testable."""
    rows = sorted(r for r in rows if r[0] != OUTPUT)
    studies: dict[str, list[str]] = defaultdict(list)
    top: list[str] = []
    blobs: dict[str, list[str]] = defaultdict(list)
    for path, blob in rows:
        parts = PurePosixPath(path).parts
        if len(parts) < 2 or parts[0] != 'analysis':
            continue
        blobs[blob].append(path)
        if len(parts) == 2:
            top.append(parts[1])
        else:
            studies[parts[1]].append('/'.join(parts[2:]))

    lines = [
        '# Index of analysis/',
        '',
        f'Generated by `{COMMAND}` from `git ls-files`. Do not edit by hand; rerun the',
        'script after adding files (`--check` reports whether this file is current).',
        '',
        'This is a map, not a cleanup. Many committed records pin paths under `analysis/`',
        'by name and SHA256, so nothing here is moved or renamed. New studies go in a',
        'dated subdirectory, as the 2026-11 studies do. The current project state is in',
        '[STATUS.md](../STATUS.md); root-level legacy files are described in',
        '[docs/LEGACY_LAYOUT.md](../docs/LEGACY_LAYOUT.md).',
        '',
        f'Tracked files: {len(rows)} ({len(top)} at the top level of `analysis/`,'
        f' {len(rows) - len(top)} in {len(studies)} subdirectories).',
        '',
        '## Studies behind the current default',
        '',
        '| Directory | Files | Start here | What it is |',
        '| --- | ---: | --- | --- |',
    ]
    for name, what in CURRENT:
        files = studies.get(name, [])
        lines.append(f'| `{name}/` | {len(files)} | {entry(name, files)} | {cell(what)} |')

    current = {name for name, _ in CURRENT}
    lines += [
        '',
        '## All study subdirectories',
        '',
        'Dates come from the directory name or, failing that, from file names inside it.',
        '',
        '| Directory | Files | Dates in names | Start here |',
        '| --- | ---: | --- | --- |',
    ]
    for name in sorted(studies):
        files = studies[name]
        label = f'`{name}/`' + (' (current)' if name in current else '')
        when = dates([name]) or dates(files)
        lines.append(f'| {label} | {len(files)} | {when} | {entry(name, files)} |')

    groups: dict[str, list[str]] = defaultdict(list)
    for name in top:
        groups[family(name)].append(name)
    small = sorted(n for key, names in groups.items() if len(names) < MIN_FAMILY for n in names)
    big = sorted(((key, names) for key, names in groups.items() if len(names) >= MIN_FAMILY),
                 key=lambda kv: (-len(kv[1]), kv[0]))
    lines += [
        '',
        '## Top-level files by name prefix',
        '',
        'Most of these are Nov 2026 plans, protocols, audits and results from the 0.9.x',
        'research lineage. Several large JSON files here are inputs to',
        '`scripts/report/build_report.py`, which is another reason they stay in place.',
        f'Prefixes with fewer than {MIN_FAMILY} files are pooled in the last row.',
        '',
        '| Prefix | Files | Types | Dates in names | Examples |',
        '| --- | ---: | --- | --- | --- |',
    ]
    for key, names in big + ([('(other)', small)] if small else []):
        names = sorted(names)
        kinds = defaultdict(int)
        for n in names:
            kinds[n.rsplit('.', 1)[-1] if '.' in n else '(none)'] += 1
        kind = ', '.join(f'{k} {v}' for k, v in sorted(kinds.items()))
        examples = ', '.join(f'`{cell(n)}`' for n in names[:2])
        lines.append(f'| `{cell(key)}` | {len(names)} | {kind} | {dates(names)} | {examples} |')

    copies = sorted((paths for paths in blobs.values() if len(paths) > 1),
                    key=lambda p: (-len(p), sorted(p)[0]))
    copied = sum(len(p) for p in copies)
    lines += [
        '',
        '## Byte-identical copies',
        '',
        f'{copied} tracked files under `analysis/` share their exact content with at least one',
        f'other file here ({len(copies)} distinct contents). These are deliberate provenance',
        'snapshots: each study copied the model and runtime code it executed, and its',
        'manifests pin those copies by hash. Do not merge or deduplicate them. New work',
        'should import shared code from one place instead of copying it.',
        '',
        f'Largest groups (up to {TOP_COPY_GROUPS}):',
        '',
        '| Copies | Example paths |',
        '| ---: | --- |',
    ]
    for paths in copies[:TOP_COPY_GROUPS]:
        paths = sorted(paths)
        shown = ', '.join(f'`{cell(p[len("analysis/"):])}`' for p in paths[:2])
        lines.append(f'| {len(paths)} | {shown} |')
    return '\n'.join(lines) + '\n'


def entry(name: str, files: list[str]) -> str:
    for candidate in ENTRY_POINTS:
        if candidate in files:
            return f'[{candidate}]({name}/{candidate})'
    return ''


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true', help='exit 1 if the index is stale')
    args = parser.parse_args(argv)
    text = render(tracked())
    path = ROOT / OUTPUT
    if args.check:
        current = path.read_text(encoding='utf-8') if path.exists() else ''
        if current != text:
            print(f'{OUTPUT} is out of date; run {COMMAND}', file=sys.stderr)
            return 1
        print(f'{OUTPUT} is current')
        return 0
    path.write_text(text, encoding='utf-8')
    print(f'wrote {OUTPUT}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
